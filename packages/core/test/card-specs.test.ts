import { test } from "node:test";
import assert from "node:assert/strict";
import { cardSpecTexts, planCardSpecs, readCardSpecs } from "../src/catalog";

const specs = (params: Array<[string, string]>, plan: string[], name = "", lang: "uk" | "ru" = "uk") =>
  cardSpecTexts(readCardSpecs(params.map(([n, v]) => ({ name: n, value: v })), name), plan, lang).map((s) => s.text);

test("характеристики карточки: разные названия у поставщика — один понятный вид", () => {
  assert.deepEqual(specs([["Номінальна напруга, В", "18 (1 батарея)"]], ["voltage"]), ["18 В"]);
  assert.deepEqual(specs([["Номінальна напруга, В", "230±10%"]], ["voltage"]), ["230 В"]);
  assert.deepEqual(specs([["Номінальна потужність, Вт", "922"]], ["power"]), ["922 Вт"]);
  assert.deepEqual(specs([["Номінальна потужність, кВт", "0,36"]], ["power"]), ["0,36 кВт"]);
  assert.deepEqual(specs([["Максимальна потужність, Вт", "1300"]], ["power"]), ["1300 Вт"], "«максимальна» — это не «к.с.»");
  assert.deepEqual(specs([["Потужність двигуна, к. с.", "15,0"]], ["power"]), ["15 к.с."]);
  assert.deepEqual(specs([["Потужність, к.с./кВт", "2,0/1,5"]], ["power"]), ["1,5 кВт"]);
  assert.deepEqual(specs([["Максимальна потужність споживання, кВА", "4,5"]], ["power"]), ["4,5 кВА"]);
  assert.deepEqual(specs([["Тип двигуна", "Інверторний, безщітковий"]], ["engine"]), ["Безщітковий"]);
  assert.deepEqual(specs([["Тип двигуна", "двотактний бензиновий одноциліндровий"]], ["engine"], "", "ru"), ["2-тактный"]);
  assert.deepEqual(specs([["Максимальний крутний момент, Н·м", "1-й режим швидкості: 32, 2-й режим швидкості: 17"]], ["torque"]), ["32 Н·м"]);
  assert.deepEqual(specs([["Діаметр свердла", "10.5"], ["Довжина свердла", "133"]], ["drillDiameter", "length"]), ["Ø 10,5 мм", "133 мм"]);
  assert.deepEqual(specs([["Кількість зубiв", "60"]], ["teeth"], "", "ru"), ["60 зубьев"]);
  assert.deepEqual(specs([["Кількість зубів на дюйм", "10 TPI"]], ["teeth"]), ["10 TPI"]);
  assert.deepEqual(specs([["Зернистість", "P 80"]], ["grit"]), ["P80"]);
  assert.deepEqual(specs([["Діаметр посадкового отвору, мм", "22,2/25,4"]], ["landing"]), ["посадка 22,2/25,4"]);
  assert.deepEqual(specs([["Довжина шини, дюйм (см)", "14\" (35 см)"]], ["bar"]), ["шина 35 см"]);
  assert.deepEqual(specs([["Ємність, А·год", "4"]], ["capacity"]), ["4 А·год"]);
  assert.deepEqual(specs([["Ємність акумулятора, мА·год", "5200"]], ["capacity"]), ["5200 мА·год"]);
});

test("характеристики карточки: единицы не путаются (г/кг, см/м), наборы длин не показываются", () => {
  assert.deepEqual(specs([["Маса нетто/брутто, кг", "0,64/0,7"]], ["weight"]), ["0,64 кг"]);
  assert.deepEqual(specs([["Вага, г", "500"]], ["weight"]), ["500 г"]);
  assert.deepEqual(specs([["Довжина, см", "80"]], ["length"]), ["80 см"]);
  assert.deepEqual(specs([["Довжина, м", "20"]], ["length"]), ["20 м"]);
  assert.deepEqual(specs([["Довжина", "25 мм"]], ["length"]), ["25 мм"]);
  assert.deepEqual(specs([["Довжина, мм", "75; 100; 150"]], ["length"]), [], "набор длин — не одна характеристика");
  assert.deepEqual(specs([["Кількість в упаковці", "1 од."]], ["packQty"]), [], "1 штука — не стоит места на карточке");
  assert.deepEqual(specs([["Кількість в упаковці", "10 од."]], ["packQty"]), ["10 шт"]);
});

test("характеристики карточки: АКБ в комплекте — по названию (Kit) или по «Комплектації»", () => {
  assert.deepEqual(specs([["Номінальна напруга, В", "18"]], ["kit", "voltage"], "Дриль-шуруповерт Vitals Master AU 1832c BL Kit"), ["З АКБ і ЗП", "18 В"]);
  assert.deepEqual(specs([["Комплектація", "АКБ і зарядний пристрій до комплекту не входять"]], ["kit"], "Пила Vitals AKZ 1810"), ["Без АКБ"]);
  assert.deepEqual(specs([["Номінальна напруга, В", "18"]], ["kit", "voltage"], "Пила Vitals AKZ 1810"), ["18 В"], "ничего не известно — не пишем");
});

test("план подраздела: только то, что есть у многих и отличается; по важности; не больше трёх", () => {
  const p = (params: Array<[string, string]>, name = "") => readCardSpecs(params.map(([n, v]) => ({ name: n, value: v })), name);
  const drills = [
    p([["Діаметр свердла", "5"], ["Довжина свердла", "86"], ["Призначення", "по металу"], ["Кількість в упаковці", "10 од."], ["Матеріал", "сталь HSS 4241"]]),
    p([["Діаметр свердла", "8"], ["Довжина свердла", "117"], ["Призначення", "по металу"], ["Кількість в упаковці", "5 од."], ["Матеріал", "сталь HSS 4241"]]),
    p([["Діаметр свердла", "10"], ["Довжина свердла", "133"], ["Призначення", "по металу"], ["Кількість в упаковці", "5 од."], ["Матеріал", "сталь HSS-Co"]]),
    p([["Діаметр свердла", "12"], ["Довжина свердла", "151"], ["Призначення", "по металу"], ["Кількість в упаковці", "2 од."], ["Матеріал", "сталь HSS 4241"]]),
  ];
  // «Призначення: по металу» у всех одинаковое — бесполезно; материал менее важен, чем количество
  assert.deepEqual(planCardSpecs(drills), ["drillDiameter", "length", "packQty", "material"]);
  assert.deepEqual(planCardSpecs(drills, 3), ["drillDiameter", "length", "packQty"]);
  const tools = [
    p([["Номінальна напруга, В", "18"], ["Номінальна потужність, Вт", "400"], ["Тип двигуна", "безщітковий"]], "Шуруповерт X Kit"),
    p([["Номінальна напруга, В", "12"], ["Номінальна потужність, Вт", "250"], ["Тип двигуна", "щітковий"]], "Шуруповерт Y"),
    p([["Номінальна напруга, В", "18"], ["Номінальна потужність, Вт", "600"], ["Тип двигуна", "безщітковий"]], "Гайковерт Z"),
  ];
  assert.deepEqual(planCardSpecs(tools), ["kit", "voltage", "power", "engine"], "«АКБ у комплекті» — первой, если встречается");
  // на карточке — не больше трёх из плана, только те, что есть у товара
  assert.deepEqual(specs([["Номінальна напруга, В", "18"], ["Максимальний крутний момент, Н·м", "350"], ["Номінальна потужність, Вт", "922"]], ["kit", "voltage", "torque", "power"], "Гайковерт"), ["18 В", "350 Н·м", "922 Вт"]);
  assert.deepEqual(specs([["Номінальна напруга, В", "18"], ["Номінальна потужність, Вт", "400"]], ["kit", "voltage", "torque", "power"], "Пила"), ["18 В", "400 Вт"]);
  assert.deepEqual(planCardSpecs([]), []);
});
