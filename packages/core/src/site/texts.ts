/** Все тексты: сначала новые (витрина), потом перенесённые из прототипа. */
export const TEXT_ENTRIES: TextEntry[] = [...NEW_TEXTS, ...legacy()];
export const TEXT_BY_KEY: ReadonlyMap<string, TextEntry> = new Map(TEXT_ENTRIES.map((e) => [e.key, e]));
export const isKnownTextKey = (key: string) => TEXT_BY_KEY.has(key);

export const toLang = (l: DbLocale): Lang => (l === "UK" ? "uk" : "ru");
export const toDbLocale = (l: Lang): DbLocale => (l === "uk" ? "UK" : "RU");

export type TextOverrideRow = { key: string; lang: DbLocale; value: string };

/** Стандартные тексты на языке (без правок владельца). */
export function defaultTexts(lang: Lang): Record<string, string> {
  return Object.fromEntries(TEXT_ENTRIES.map((e) => [e.key, e[lang]]));
}

/** Тексты на языке с учётом правок: правка побеждает, пустая правка и чужие ключи игнорируются. */
export function resolveTexts(overrides: TextOverrideRow[], lang: Lang): Record<string, string> {
  const out = defaultTexts(lang);
  for (const o of overrides) {
    if (toLang(o.lang) !== lang || !TEXT_BY_KEY.has(o.key)) continue;
    if (o.value.trim() !== "") out[o.key] = o.value;
  }
  return out;
}

/**
 * Что записать в базу при сохранении поля: пустое или равное стандартному значение — правки нет (вернуть стандартное).
 * Возвращает null, если правку надо удалить, иначе — очищенный текст.
 */
export function normalizeTextEdit(key: string, lang: Lang, raw: string): string | null {
  const entry = TEXT_BY_KEY.get(key);
  if (!entry) return null;
  // eslint-disable-next-line no-control-regex
  const value = raw.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "").replace(/\r\n?/g, "\n").trim().slice(0, MAX_TEXT_LENGTH);
  return value === "" || value === entry[lang] ? null : value;
}

/** Подставляет {n}, {name} и т. п. Неизвестные переменные остаются как есть. */
export function fillText(text: string, vars: Record<string, string | number> = {}): string {
  return text.replace(/\{([a-zA-Z]+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Переменные, которые есть в стандартном тексте: их владельцу нельзя потерять при правке. */
export function textVars(entry: TextEntry): string[] {
  return [...new Set([...entry.uk.matchAll(/\{([a-zA-Z]+)\}/g)].map((m) => m[1]))];
}

/** Проверка правки: все переменные стандартного текста должны остаться. Возвращает пропавшие. */
export function missingVars(entry: TextEntry, value: string): string[] {
  return textVars(entry).filter((v) => !value.includes(`{${v}}`));
}

/** Число с правильным словом: 1 товар, 2 товари, 5 товарів (для рус. — товар, товара, товаров). */
export function pluralIndex(n: number): "one" | "few" | "many" {
  const m10 = Math.abs(n) % 10;
  const m100 = Math.abs(n) % 100;
  if (m10 === 1 && m100 !== 11) return "one";
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return "few";
  return "many";
}

/** «5 товарів» из набора текстов (ключи unit.<name>.one/few/many). */
export function countWord(texts: Record<string, string>, unit: string, n: number): string {
  return `${n} ${texts[`unit.${unit}.${pluralIndex(n)}`] ?? ""}`.trim();
}

/** Список групп с записями — для админки. Пустые группы пропускаются. */
export function groupedEntries(): Array<{ group: string; entries: TextEntry[] }> {
  return TEXT_GROUPS.map((group) => ({ group, entries: TEXT_ENTRIES.filter((e) => e.group === group) })).filter((g) => g.entries.length > 0);
}
