/** Синонимы в формате Meilisearch: слово → все остальные слова группы (в обе стороны). */
export function synonymMap(groups: string[][] = SYNONYM_GROUPS): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const group of groups) {
    const words = [...new Set(group.map((w) => w.toLowerCase()))];
    for (const w of words) out[w] = [...new Set([...(out[w] ?? []), ...words.filter((x) => x !== w)])];
  }
  return out;
}
