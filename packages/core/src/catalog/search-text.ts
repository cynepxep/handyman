// Тексты поиска: исправление раскладки клавиатуры и стартовые синонимы.

const LAT = "qwertyuiop[]asdfghjkl;'zxcvbnm,.`";
// Раскладка ЙЦУКЕН (русская) и украинская: различаются буквами на клавишах s ] ' \ `
const RU = "йцукенгшщзхъфывапролджэячсмитьбюё";
const UK = "йцукенгшщзхїфівапролджєячсмитьбюʼ";

function convert(text: string, table: string): string {
  let out = "";
  for (const ch of text) {
    const lower = ch.toLowerCase();
    const i = LAT.indexOf(lower);
    if (i < 0) {
      out += ch;
      continue;
    }
    const mapped = table[i];
    out += ch === lower ? mapped : mapped.toUpperCase();
  }
  return out;
}

const CYR = /[Ѐ-ӿ]/g;
const LATIN_LETTER = /[a-z]/i;

/**
 * «rheu» → «круг». Возвращает варианты запроса, набранного не в той раскладке
 * (сначала украинская, потом русская, если отличается). Пусто, если запрос не похож на такой случай.
 */
export function fixKeyboardLayout(query: string): string[] {
  const q = query.trim();
  if (!q || !LATIN_LETTER.test(q) || /[Ѐ-ӿ]/.test(q)) return [];
  const variants = new Set<string>();
  for (const table of [UK, RU]) {
    const converted = convert(q, table);
    const cyr = (converted.match(CYR) ?? []).length;
    const letters = converted.replace(/[^\p{L}]/gu, "").length;
    if (letters > 0 && cyr / letters >= 0.6 && converted !== q) variants.add(converted);
  }
  return [...variants];
}

